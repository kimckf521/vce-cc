type Diff = "EASY" | "MEDIUM" | "HARD";
type ItemType = "MCQ" | "SHORT_ANSWER" | "EXTENDED_ANSWER" | "EXTENDED_RESPONSE";
interface Item {
  type: ItemType;
  marks: number;
  difficulty: Diff;
  topicSlug: string;
  subtopicSlugs: string[];
  content: string;
  preamble?: string | null;
  parts?: Array<{ label: string; marks: number; content: string; solution: string }> | null;
  optionA?: string;
  optionB?: string;
  optionC?: string;
  optionD?: string;
  correctOption?: "A" | "B" | "C" | "D";
  solutionContent?: string | null;
}

function mcq(
  topic: string,
  sub: string,
  content: string,
  opts: [string, string, string, string],
  k: "A" | "B" | "C" | "D",
  d: Diff,
  sol: string,
): Item {
  return {
    type: "MCQ",
    marks: 1,
    difficulty: d,
    topicSlug: topic,
    subtopicSlugs: [sub],
    content,
    optionA: opts[0],
    optionB: opts[1],
    optionC: opts[2],
    optionD: opts[3],
    correctOption: k,
    solutionContent: sol,
  };
}
function sa(
  topic: string,
  sub: string,
  content: string,
  marks: number,
  d: Diff,
  sol: string,
): Item {
  return { type: "SHORT_ANSWER", marks, difficulty: d, topicSlug: topic, subtopicSlugs: [sub], content, solutionContent: sol };
}
function ea(
  topic: string,
  sub: string,
  preamble: string,
  d: Diff,
  parts: Array<{ label: string; marks: number; content: string; solution: string }>,
): Item {
  return {
    type: "EXTENDED_ANSWER",
    marks: parts.reduce((s, p) => s + p.marks, 0),
    difficulty: d,
    topicSlug: topic,
    subtopicSlugs: [sub],
    preamble,
    parts,
    content: "",
  };
}
function er(
  topic: string,
  sub: string,
  preamble: string,
  d: Diff,
  parts: Array<{ label: string; marks: number; content: string; solution: string }>,
): Item {
  return {
    type: "EXTENDED_RESPONSE",
    marks: parts.reduce((s, p) => s + p.marks, 0),
    difficulty: d,
    topicSlug: topic,
    subtopicSlugs: [sub],
    preamble,
    parts,
    content: "",
  };
}

